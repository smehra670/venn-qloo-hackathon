/**
 * Captures Research screen steps for visual QA vs the map-and-motion reference.
 *
 * Requires Vite on :5173 (or VENN_URL). Uses Playwright Chromium when available.
 *
 *   npx --yes playwright@1.55.0 install chromium
 *   node scripts/capture-research.mjs
 *
 * Output: docs/screens/research/{desktop|mobile|reduced|zero|unknown}/…
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "docs", "screens", "research");
const BASE = process.env.VENN_URL ?? "http://localhost:5173";

const STEPS = ["resolve", "plan", "discover", "score", "enrich", "adapt", "assemble"];

/** Mid-step elapsed ms so motion isn't stuck at t=0. */
const STEP_ELAPSED = {
  resolve: 1400,
  plan: 1200,
  discover: 2400,
  score: 1400,
  enrich: 1200,
  adapt: 1200,
  assemble: 2800,
};

const VIEWPORTS = {
  desktop: { width: 1440, height: 900 },
  mobile: { width: 390, height: 844 },
};

async function waitForResearch(page) {
  await page.waitForSelector("h1", { timeout: 30_000 });
  // Map path: wait until MapLibre reports load+idle. Unknown-city keeps CirclesLoader.
  const isUnknown = page.url().includes("unknown-city");
  if (isUnknown) {
    await page.waitForSelector('[data-testid="circles-loader"], .circles-loader', {
      timeout: 20_000,
    });
    await page.waitForTimeout(400);
    return;
  }
  try {
    await page.waitForSelector('[data-research-map-ready="1"]', { timeout: 25_000 });
  } catch {
    /* still screenshot whatever rendered */
  }
  try {
    await page.waitForSelector('[data-research-map-idle="1"]', { timeout: 12_000 });
  } catch {
    /* tiles may still be settling */
  }
  // Extra beat so OpenFreeMap tiles paint after camera ease
  await page.waitForTimeout(2200);
  // Discover should show the radar sweep over You
  if (page.url().includes("step=discover") && !page.url().includes("scenario=zero")) {
    try {
      await page.waitForSelector('[data-research-radar="1"]', { timeout: 5_000 });
    } catch {
      /* still capture */
    }
  }
}

async function shot(page, dir, name) {
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, `${name}.png`);
  await page.screenshot({ path: file, fullPage: false });
  console.log("wrote", path.relative(ROOT, file));
}

async function gotoShot(page, { step, scenario = "default", done = false, t }) {
  const params = new URLSearchParams();
  params.set("step", step);
  if (scenario !== "default") params.set("scenario", scenario);
  if (done) params.set("done", "1");
  if (t != null) params.set("t", String(t));
  const url = `${BASE}/#research-shot?${params.toString()}`;
  await page.goto(url, { waitUntil: "domcontentloaded", timeout: 60_000 });
  await waitForResearch(page);
}

async function main() {
  let chromium;
  try {
    ({ chromium } = await import("playwright"));
  } catch {
    console.warn("Playwright not installed — run: npx playwright@1.55.0 install chromium");
    process.exit(1);
  }

  await mkdir(OUT, { recursive: true });
  const browser = await chromium.launch({ headless: true });

  try {
    for (const [vpName, viewport] of Object.entries(VIEWPORTS)) {
      const page = await browser.newPage({ viewport });
      const dir = path.join(OUT, vpName);
      for (const step of STEPS) {
        await gotoShot(page, { step, t: STEP_ELAPSED[step] });
        await shot(page, dir, step);
      }
      // Finished assemble (CTA state)
      await gotoShot(page, { step: "assemble", done: true, t: 5000 });
      await shot(page, dir, "assemble-done");
      await page.close();
    }

    // Reduced motion → finished state
    {
      const page = await browser.newPage({
        viewport: VIEWPORTS.desktop,
        reducedMotion: "reduce",
      });
      await gotoShot(page, { step: "assemble", done: true, t: 5000 });
      await shot(page, path.join(OUT, "reduced-motion"), "assemble-done");
      await page.close();
    }

    // Zero results — sweep stopped, empty message
    {
      const page = await browser.newPage({ viewport: VIEWPORTS.desktop });
      await gotoShot(page, { step: "discover", scenario: "zero", t: 1800 });
      await shot(page, path.join(OUT, "zero"), "discover");
      await page.close();
    }

    // Unknown city — CirclesLoader fallback
    {
      const page = await browser.newPage({ viewport: VIEWPORTS.desktop });
      await gotoShot(page, { step: "resolve", scenario: "unknown-city", t: 1400 });
      await shot(page, path.join(OUT, "unknown-city"), "resolve");
      await page.close();
    }

    await writeFile(
      path.join(OUT, "README.md"),
      [
        "# Research screen captures",
        "",
        "Generated by `node scripts/capture-research.mjs`.",
        "",
        "- `desktop/` `mobile/` — each of the 7 steps at mid-motion, plus `assemble-done`",
        "- `reduced-motion/` — finished state with prefers-reduced-motion",
        "- `zero/` — no places nearby",
        "- `unknown-city/` — CirclesLoader fallback (no coordinates)",
        "",
        "Compare visually with `venn-research-reference.html` (design reference).",
        "",
      ].join("\n"),
      "utf8",
    );
  } finally {
    await browser.close();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
