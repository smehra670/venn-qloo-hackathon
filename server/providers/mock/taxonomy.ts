export function lookupSynonyms(raw: string): TagId[] {
  const text = raw.toLowerCase().trim();
  const tags = new Set<TagId>();
  const direct = SYNONYMS[text];
  if (direct) tags.add(direct);
  const tokens = text.split(/[^a-z0-9+]+/).filter((token) => token.length > 0);
  for (let i = 0; i < tokens.length - 1; i += 1) {
    const left = tokens[i];
    const right = tokens[i + 1];
    if (!left || !right) continue;
    const bigram = SYNONYMS[`${left} ${right}`];
    if (bigram) tags.add(bigram);
  }
  for (const token of tokens) {
    const hit = SYNONYMS[token];
    if (hit) tags.add(hit);
  }
  return [...tags];
}
